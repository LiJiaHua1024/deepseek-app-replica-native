#!/usr/bin/env python3
"""gen_tokens.py — mechanically extract design tokens from the reference
CSS (theme.css + android.css) and emit Tokens.kt for the Compose app.
No literals in UI code — everything flows from here.
"""
import re
import sys
from pathlib import Path

REF = Path('/tmp/webview-reference')
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('Tokens.kt')

def parse_vars(text):
    """Return list of (selector, {var: value})."""
    blocks = []
    for m in re.finditer(r'([^{}]+)\{([^{}]+)\}', text, re.S):
        sel, body = m.group(1).strip(), m.group(2)
        vs = dict(re.findall(r'(--[\w-]+)\s*:\s*([^;]+);', body))
        if vs:
            blocks.append((sel, vs))
    return blocks

def rgba(v):
    v = v.strip()
    m = re.match(r'rgba?\(([^)]+)\)', v)
    if m:
        parts = [p.strip() for p in m.group(1).split(',')]
        r, g, b = (float(parts[i]) for i in range(3))
        a = float(parts[3]) if len(parts) > 3 else 1.0
        return (int(r), int(g), int(b), a)
    if v.startswith('#'):
        h = v[1:]
        if len(h) == 3:
            h = ''.join(c * 2 for c in h)
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0)
    return None

def camel(name):
    name = re.sub(r'^--dsw-(alias|static|specific)-?', '', name)
    name = name.replace('darkmode', 'Darkmode')
    return re.sub(r'-(\w)', lambda m: m.group(1).upper(), name)

def kotlin_color(t):
    r, g, b, a = t
    if a >= 1.0:
        return 'Color(0xFF%02X%02X%02X)' % (r, g, b)
    return 'Color(%d, %d, %d, %d)' % (r, g, b, round(a * 255))

theme = (REF / 'src/app/theme.css').read_text()
android = (REF / 'src/app/android.css').read_text()
blocks = parse_vars(theme)

# gather static + alias maps for light/dark
def collect(pred):
    out = {}
    for sel, vs in blocks:
        if pred(sel):
            out.update(vs)
    return out

dark_static = collect(lambda s: 'data-ds-dark-theme' in s)
light_static = collect(lambda s: s == 'body')
light_alias = {k: v for k, v in light_static.items() if k.startswith('--dsw-alias') or k.startswith('--dsw-specific')}
dark_alias = {k: v for k, v in dark_static.items() if k.startswith('--dsw-alias') or k.startswith('--dsw-specific')}
statics_light = {k: v for k, v in light_static.items() if k.startswith('--dsw-static')}
statics_dark = {k: v for k, v in dark_static.items() if k.startswith('--dsw-static')}
shadows = {k: v for k, v in light_static.items() if k.startswith('--dsw-shadow')}
fonts = {k: v for k, v in light_static.items() if k.startswith('--dsw-font-') or k.startswith('--ds-font-')}
controls = {k: v for k, v in light_static.items() if k.startswith('--ds-control') or k.startswith('--ds-transition') or k.startswith('--ds-ease')}

# android light overrides
for sel, vs in parse_vars(android):
    if 'not([data-ds-dark-theme])' in sel:
        light_alias.update({k: v for k, v in vs.items() if k.startswith('--dsw-')})

def resolve(v, alias_map, stat_map, depth=0):
    v = v.strip()
    m = re.match(r'var\((--[\w-]+)\)', v)
    if m and depth < 6:
        k = m.group(1)
        if k in alias_map:
            return resolve(alias_map[k], alias_map, stat_map, depth + 1)
        if k in stat_map:
            return resolve(stat_map[k], alias_map, stat_map, depth + 1)
        return v
    return v

def kt_name(v):
    return camel(v)

# ---- emit --------------------------------------------------------------------
lines = ['// generated by tools/gen_tokens.py from reference theme.css + android.css',
         '// do not edit by hand — re-run the generator',
         'package io.github.lijiahua1024.dsnative.ui.theme', '',
         'import androidx.compose.ui.graphics.Color',
         'import androidx.compose.ui.text.TextStyle',
         'import androidx.compose.ui.text.font.FontWeight',
         'import androidx.compose.ui.unit.sp',
         'import androidx.compose.ui.unit.dp', '']

lines.append('object DsStatics {')
for k in sorted(statics_light):
    c = rgba(resolve(statics_light[k], {}, statics_light))
    if c:
        lines.append('    val %s = %s' % (kt_name(k), kotlin_color(c)))
lines.append('}')
lines.append('')

all_keys = sorted(set(light_alias) | set(dark_alias))
lines.append('data class DsColors(')
for k in all_keys:
    lines.append('    val %s: Color,' % kt_name(k))
lines.append(')')
lines.append('')

for label, amap, smap in (('dsLightColors', light_alias, statics_light),
                          ('dsDarkColors', dark_alias, statics_dark)):
    lines.append('val %s = DsColors(' % label)
    for k in all_keys:
        raw = amap.get(k)
        if raw is None:
            raw = light_alias[k]
            smap2 = statics_light
        else:
            smap2 = smap
        c = rgba(resolve(raw, amap, smap2))
        if c is None:
            print('WARN unresolved', label, k, raw)
            lines.append('    %s = Color.Magenta, // UNRESOLVED %s' % (kt_name(k), raw))
        else:
            lines.append('    %s = %s,' % (kt_name(k), kotlin_color(c)))
    lines.append(')')
    lines.append('')

# fonts: weight size/lineHeight
lines.append('object DsFont {')
for k in sorted(fonts):
    if 'family' in k or 'font-family' in k:
        continue
    m = re.match(r'(?:inherit|(?:\d{3})\s+)?([\d.]+)px\s*/\s*([\d.]+)px', fonts[k])
    w = re.match(r'(\d{3})\s+', fonts[k])
    name = kt_name(k.replace('--dsw-font-', '').replace('--ds-font-', 'ds'))
    if m:
        wmap = {'400': 'Normal', '500': 'Medium', '600': 'SemiBold', '700': 'Bold', '900': 'Black'}
        wt = wmap.get(w.group(1) if w else '400', 'Normal')
        lines.append('    val %s = TextStyle(fontSize = %g.sp, lineHeight = %g.sp, fontWeight = FontWeight.%s)'
                     % (name, float(m.group(1)), float(m.group(2)), wt))
    else:
        # plain size tokens like --ds-font-size-m: 14px
        m2 = re.match(r'([\d.]+)px', fonts[k])
        if m2:
            lines.append('    val %s = %g.sp' % (name, float(m2.group(1))))
lines.append('}')
lines.append('')

lines.append('object DsSize {')
for k in sorted(controls):
    m = re.match(r'([\d.]+)px', controls[k])
    if m:
        ident = camel(k)
        if ident and ident[0] == '-':
            ident = 'ds' + re.sub(r'-(\w)', lambda m: m.group(1).upper(), ident[1:])
        lines.append('    val %s = %g.dp' % (ident, float(m.group(1))))
lines.append('    val composerBottom = 27.dp')
lines.append('    val composerBottomButtons = 21.dp')
lines.append('    val composerBottomKeyboard = 11.dp')
lines.append('    val transitionDuration = 200')
lines.append('    val transitionDurationSlow = 300')
lines.append('}')
lines.append('')
lines.append('// --dsw-shadow-lv3: 0 0 1px rgba(0,0,0,.2), 0 0 4px rgba(0,0,0,.02), 0 12px 32px rgba(0,0,0,.08)')

OUT.write_text('\n'.join(lines) + '\n')
print('wrote %s: %d statics, %d aliases, %d fonts' % (OUT, len(statics_light), len(all_keys), len(fonts)))
